'use strict';

// Единственный источник истины для входных ограничений загрузки фотографий
// в YAAM HQ.
//
// Выделен в отдельный модуль без зависимостей намеренно: эти же числа нужны
// и слою представления (hq/photosViews.js — атрибуты формы и текст ошибки),
// и роутам (multer), и операционной проверке диска. Раньше слой
// представления дублировал константу литералом, потому что подключать ради
// одного числа imagePipeline (а с ним sharp) в шаблон неправильно. Теперь
// literal нет ни в одном месте — все читают отсюда.
//
// Разделение обязанностей у трёх лимитов ниже разное, и подменять один
// другим нельзя:
//
//   MAX_SOURCE_BYTES        — сколько байт запроса YAAM согласен ВРЕМЕННО
//                             принять на обработку. Это НЕ размер хранения:
//                             исходные байты никогда не сохраняются, после
//                             пайплайна остаются только WebP-варианты.
//   MAX_SOURCE_DIMENSION_PX — предел по каждой стороне.
//   MAX_SOURCE_PIXELS       — предел по площади, защита от decompression
//                             bomb: маленький файл, разворачивающийся в
//                             гигантский растр, отсекается по площади ещё
//                             до декодирования пикселей.
//
// 40 МиБ по байтам: обычный кадр современной камеры/телефона в максимальном
// качестве — это 18-25 МиБ (реальный пример из фотосессии ресторана:
// 5152x7728, 21.4 МиБ). Прежние 15 МиБ такие файлы отклоняли, и владелец
// был вынужден пережимать фотографию руками до загрузки. 40 МиБ снимает эту
// нагрузку с владельца, оставаясь конечным и защищённым числом.
//
// Пиксельные лимиты СОЗНАТЕЛЬНО не поднимались: 5152x7728 = 39.81 Мп
// укладывается в 40 Мп, а всё, что больше, — уже не «обычная фотография
// блюда», и декодировать это в память одного VPS небезопасно.
const MAX_SOURCE_BYTES = 40 * 1024 * 1024; // 40 МиБ
const MAX_SOURCE_DIMENSION_PX = 8000; // по каждой стороне
const MAX_SOURCE_PIXELS = 40_000_000; // ~40 Мп

function formatMebibytes(bytes) {
  return Math.floor(bytes / 1024 / 1024);
}

// Один и тот же текст показывают и клиентская проверка (hq/static/hq.js), и
// сервер, чтобы владелец не видел два разных сообщения об одном и том же.
const TOO_LARGE_MESSAGE =
  `Фото слишком большое. Максимальный размер исходного файла — ${formatMebibytes(MAX_SOURCE_BYTES)} МБ.`;

module.exports = {
  MAX_SOURCE_BYTES,
  MAX_SOURCE_DIMENSION_PX,
  MAX_SOURCE_PIXELS,
  TOO_LARGE_MESSAGE,
  formatMebibytes,
};
