-- 0011_payment_receipt_url — Stage 31, раздел 3.
--
-- ИССЛЕДОВАНИЕ (задание требует проверить ПЕРЕД добавлением ссылки в
-- Telegram-сообщение): в текущей платёжной модели НЕТ ни одного места, где
-- хранился бы безопасный публичный URL чека оплаты. `payments` содержит
-- только provider/provider_payment_id/amount/status — никакого receipt-URL.
-- `fiscal_receipts` (миграция более раннего этапа) — техническая основа
-- под 54-ФЗ, НЕ подключённая ни к какой реальной кассе (см. её собственный
-- комментарий в schema.sql: "техническая основа, не подключённая ни к
-- какой реальной кассе"), и тоже не содержит URL. mock-провайдер ничего
-- похожего на ссылку никогда не выдаёт. Это подтверждённый архитектурный
-- пробел, а не то, что можно было бы просто "прочитать откуда-то ещё".
--
-- РЕШЕНИЕ ЭТОЙ МИГРАЦИИ — минимально правильное хранение (одна из двух
-- опций, разрешённых заданием), а не выдумывание работающей ссылки:
-- nullable-колонка, готовая принять безопасный публичный URL, когда он
-- РЕАЛЬНО появится (интеграция настоящего YooKassa receipt flow — вне
-- объёма Stage 31). Ничто в текущем коде эту колонку не заполняет —
-- это осознанно (см. STAGE31 отчёт, раздел 3): показывать "Чек оплаты" в
-- Telegram-сообщении можно и нужно ТОЛЬКО когда значение реально есть,
-- никогда — по факту наличия колонки.
--
-- НЕ payment_url и НЕ confirmation_url: тот внутренний URL провайдера уже
-- существует в других местах (currentPaymentUrl на клиенте) и предназначен
-- ТОЛЬКО для оплаты, не для просмотра постфактум — путать его с публичной
-- ссылкой на уже пробитый чек означало бы риск раскрыть внутренний
-- платёжный переход как будто это чек (задание, раздел 3: "не раскрывать
-- внутренние ссылки, токены или платёжные credentials").
ALTER TABLE payments ADD COLUMN IF NOT EXISTS receipt_url TEXT;
