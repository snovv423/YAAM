-- 0006_manual_payout_and_category_restore — Stage 25.
--
-- Миграция АДДИТИВНА: ни одна существующая колонка не удаляется и не меняет
-- тип, ни одна строка не переписывается. Существующий код продолжает
-- работать без изменений — новые колонки либо nullable, либо DEFAULT.
--
-- Содержание:
--   1. payout_attempts.method / confirmed_by — закрытие разрыва Stage 24
--      HIGH-1: владелец подтверждает уже совершённый банковский перевод
--      вручную, используя ТУ ЖЕ модель обязательство/попытка, что и будущая
--      T-Bank интеграция — без второго параллельного финансового контура.
--   2. menu_items.archived_with_category_id — закрытие Stage 24 MEDIUM-1:
--      провязка «это блюдо архивировано ВМЕСТЕ с категорией», а не угадывание
--      по совпадению дат.
--
-- Новых значений в hq_audit_log_action_check и hq_events CHECK не требуется:
-- обе точки использования этой миграции переиспользуют уже существующие
-- допустимые значения ('payout_attempt_succeeded', 'payout_succeeded',
-- 'category_restored', 'settlement_document_token_issued', 'other').

-- =========================================================================
-- 1. РУЧНОЕ ПОДТВЕРЖДЕНИЕ ВЫПЛАТЫ
-- =========================================================================
--
-- ПОЧЕМУ НЕ ВТОРОЙ КОНТУР. Переходы обязательства (prepared -> processing ->
-- succeeded) и попытки (INSERT сразу в succeeded — CHECK требует только
-- completed_at NOT NULL, что уже верно) используют РОВНО ТЕ ЖЕ таблицы,
-- триггеры и CHECK-ограничения, что и будущая T-Bank попытка. Единственное
-- дополнение — как отличить ручное подтверждение от банковского в интерфейсе,
-- чтобы никогда не написать «отправлено через Т-Банк» про перевод, который
-- сделал сам владелец.
ALTER TABLE payout_attempts ADD COLUMN IF NOT EXISTS method TEXT NOT NULL DEFAULT 'tbank';
ALTER TABLE payout_attempts DROP CONSTRAINT IF EXISTS payout_attempts_method_check;
ALTER TABLE payout_attempts ADD CONSTRAINT payout_attempts_method_check
  CHECK (method IN ('tbank', 'manual'));

-- Кто подтвердил перевод — только для method='manual'; NULL для будущих
-- банковских попыток (подтверждает не человек, а ответ банка).
ALTER TABLE payout_attempts ADD COLUMN IF NOT EXISTS confirmed_by TEXT;

-- =========================================================================
-- 2. ВОССТАНОВЛЕНИЕ КАТЕГОРИИ ВМЕСТЕ С БЛЮДАМИ
-- =========================================================================
--
-- ПОЧЕМУ ЯВНАЯ СВЯЗЬ, А НЕ СОВПАДЕНИЕ ДАТ. archiveCategoryWithItems()
-- архивирует категорию и её блюда в ОДНОЙ транзакции, поэтому их archived_at
-- совпадёт технически — но это подобие, а не доказательство: два независимых
-- archiveMenuItem() в разных запросах теоретически тоже могут получить
-- одинаковый NOW(), и наоборот, повторный прогон этой же миграции когда-нибудь
-- в будущем не должен зависеть от такого совпадения. Явная ссылка убирает
-- любую двусмысленность: NULL значит «архивировано независимо от категории»
-- и никогда не восстанавливается автоматически вместе с ней.
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS archived_with_category_id INTEGER
  REFERENCES categories(id);
