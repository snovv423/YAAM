-- 0009_restaurant_candidate_votes — Stage 29.1, п.3.
--
-- Голосование "Кого ждём" (0007) до этой миграции было персистентным только
-- на стороне СПИСКА кандидатов — сам голос ("+" на клиенте) менял счётчик
-- ТОЛЬКО в памяти вкладки браузера: refresh стирал голос, HQ никогда не
-- видел результат ни одного реального клика.
--
-- Правило задания: "одно устройство может проголосовать один раз за каждого
-- кандидата; повторный голос с того же устройства за того же кандидата не
-- увеличивает счётчик". Устройство — анонимный случайный идентификатор,
-- генерируемый клиентом (localStorage), НЕ персональные данные — это не
-- логин и не привязка к человеку, только "тот же браузер уже нажимал".
--
-- UNIQUE(candidate_id, device_id) — единственная реальная защита от
-- повторного/гоночного голоса (тот же принцип, что и везде в проекте:
-- partial/обычный UNIQUE-индекс как последняя линия защиты, не только
-- проверка в коде — см. telegramLinkService.js, payments/refunds). ON DELETE
-- CASCADE — удалённый кандидат (раздел 2.4) автоматически теряет свои
-- голоса, новый голос за несуществующего кандидата отклоняется на уровне
-- FOREIGN KEY ещё до проверки в коде.
CREATE TABLE IF NOT EXISTS restaurant_candidate_votes (
  id SERIAL PRIMARY KEY,
  candidate_id INTEGER NOT NULL REFERENCES restaurant_candidates(id) ON DELETE CASCADE,
  device_id TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (candidate_id, device_id)
);
