-- 0007_restaurant_candidates — HQ "Кого ждём", после Stage 28.
--
-- Новая, полностью независимая сущность — НЕ ресторан. Клиентская страница
-- уже показывает голосование "Какой ресторан вы ждёте в YAAM?"
-- (CANDIDATE_RESTAURANTS в client/js/data.js), но список и цифры были
-- захардкожены в клиентском коде (комментарий там же: "Демо-цифры голосов;
-- список и цифры замените реальными кандидатами при запуске"). Эта миграция
-- даёт этому списку единственный источник истины в БД, управляемый из HQ —
-- вместо второго, рассинхронизирующегося набора данных в клиентском JS.
--
-- Осознанно НЕ ресторан и не подтаблица restaurants: ни фото, ни меню, ни
-- адреса, ни часов работы, ни статуса активен/неактивен — только то, что
-- нужно карточке голосования (название, кухня, счётчик голосов). Миграция
-- аддитивна — новая таблица, ничего существующего не меняется.
CREATE TABLE IF NOT EXISTS restaurant_candidates (
  id SERIAL PRIMARY KEY,
  name TEXT NOT NULL,
  cuisine TEXT NOT NULL DEFAULT '',
  votes INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
